#!/usr/bin/env node
/**
 * gen-book-english-words — writes `src/server/knowledge/book-english-words.generated.ts`: every word of five letters or more that
 * the APPROVED English books (prescriber's guide, Maudsley) contain, as their lexical index stores it.
 *   MINDCARE_BOOK_TOPICS_URL=postgres://postgres@127.0.0.1:55445/<db> node scripts/gen-book-english-words.mjs
 * A French clinical word is turned into English candidates by spelling rules (`cognats.ts`); a candidate counts only when the
 * books themselves contain it, so a rule can never invent a word. Book text only (no patient data), read-only transaction.
 */
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const { Client } = require("pg");
const url = process.env.MINDCARE_BOOK_TOPICS_URL;
if (!url) { console.error("MINDCARE_BOOK_TOPICS_URL is required"); process.exit(2); }

const client = new Client({ connectionString: url });
await client.connect();
try {
  await client.query("BEGIN READ ONLY");
  const { rows } = await client.query(`SELECT word, ndoc FROM ts_stat($$SELECT c.document_tsv FROM app.knowledge_chunks c
      JOIN app.knowledge_sources s ON s.id = c.source_id
     WHERE s.classification = 'C4' AND s.statut = 'active' AND s.approved_at IS NOT NULL AND s.approved_by IS NOT NULL
       AND (s.review_due_at IS NULL OR s.review_due_at > now()) AND s.superseded_by IS NULL AND c.statut = 'active'
       AND (s.titre ILIKE 'Prescriber%' OR s.titre ILIKE 'The Maudsley%')$$)
     WHERE length(word) >= 5 AND word ~ '^[a-z]+$' ORDER BY word`);
  await client.query("COMMIT");
  if (rows.length < 10000) throw new Error(`too few words (${rows.length}): wrong database?`);
  const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "server", "knowledge", "book-english-words.generated.ts");
  // One space-separated "word:passages" string: the words stay a small module, parsed once at load.
  writeFileSync(out, `/**
 * ⚠️ GENERATED by \`scripts/gen-book-english-words.mjs\` from the approved English books' lexical index — do not edit by hand.
 * Lower-case words of five letters or more, letters only, with the number of passages holding each. Used only to check an English
 * spelling of a French clinical word.
 */
export const BOOK_ENGLISH_WORDS: ReadonlyMap<string, number> = new Map(${JSON.stringify(rows.map((row) => `${row.word}:${row.ndoc}`).join(" "))}
  .split(" ").map((entry) => { const [word, passages] = entry.split(":"); return [word!, Number(passages)] as const; }));
`);
  console.log(`book English words written: ${rows.length}`);
} finally {
  await client.end();
}
