#!/usr/bin/env node
/**
 * gen-book-topics — writes `src/shared/alexa/book-topics.generated.ts`: the drugs and disorders the APPROVED books treat,
 * so Alexa sends a question about them to the books even when its hand-written lists do not know the word.
 *   MINDCARE_BOOK_TOPICS_URL=postgres://postgres@127.0.0.1:55445/<db> node scripts/gen-book-topics.mjs
 * Reads book headings only (no patient data), in a read-only transaction.
 * Sources: the drug monographs of the prescriber's guide (first heading level) and the head terms of the DSM's own index.
 * A head that is an everyday word, a record word or book scaffolding is excluded below, with its reason.
 */
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const { Client } = require("pg");
const url = process.env.MINDCARE_BOOK_TOPICS_URL;
if (!url) { console.error("MINDCARE_BOOK_TOPICS_URL is required"); process.exit(2); }

// Index heads that would capture a question about a record, the agenda or the practice, or that name the book itself.
const EXCLUDED = new Set([
  // record or practice words: "dans ses notes, il est question de sommeil ?" is a record question
  "sommeil", "diagnostic", "echelle", "identite", "attention", "medicament", "risque suicidaire", "non-observance du traitement",
  "histoire personnelle", "logement", "economiques", "professionnels", "educatifs", "education familiale", "relationnels",
  "environnement social", "groupe de soutien primaire", "contact social", "langage", "communication", "coordination",
  "respiration", "phonation", "moteurs", "mouvements", "alimentation", "adaptation", "attitude", "mental", "conduites",
  "sexuelle", "sexuelles", "substance", "substance autre", "substance/medicament", "syndrome", "cognitifs", "detresse",
  "acces aux soins medicaux et aux autres types de soins",
  // the book's own scaffolding
  "affections proposees pour des etudes supplementaires", "association americaine de psychiatrie", "cas clinique",
  "classiication internationale des maladies", "codage et enregistrement", "comorbidite", "complements en ligne",
  "contextes medico-legaux", "critere de signiicativite clinique", "criteres diagnostiques", "culturelle", "culturelles",
  "culturels", "deicit", "deinition d'un trouble mental", "differences de genre", "dsm-5", "dsm-iv et le dsm-5",
  "elements du diagnostic", "enfp", "etudes supplementaires", "evaluations de severite", "externalises", "internalises",
  "formulation culturelle", "glossaire des termes techniques", "icsd-2", "mesures d'evaluation", "organisation mondiale de la sante",
  "psychosociales", "questions culturelles", "speciications", "spectre diagnostique", "termes techniques",
  "trouble mental non speciie", "who disability assessment schedule", "vasculaire",
]);
const fold = (text) => text.normalize("NFD").replace(/\p{M}/gu, "").toLowerCase().replace(/[’]/gu, "'").replace(/\s+/gu, " ").trim();

const client = new Client({ connectionString: url });
await client.connect();
try {
  await client.query("BEGIN READ ONLY");
  const approved = `FROM app.knowledge_chunks c JOIN app.knowledge_sources s ON s.id = c.source_id
    WHERE s.classification = 'C4' AND s.statut = 'active' AND s.approved_at IS NOT NULL AND s.approved_by IS NOT NULL
      AND (s.review_due_at IS NULL OR s.review_due_at > now()) AND s.superseded_by IS NULL AND c.statut = 'active'`;
  const drugs = (await client.query(`SELECT DISTINCT split_part(c.section, ' › ', 1) AS head ${approved}
      AND s.titre ILIKE 'Prescriber%' AND c.section NOT LIKE 'Back matter%' AND c.section NOT LIKE 'Front matter%'`)).rows;
  const index = (await client.query(`SELECT DISTINCT split_part(c.section, ' › ', 3) AS head ${approved}
      AND s.titre ILIKE 'DSM%' AND c.section LIKE 'Annexes › Index › %'`)).rows;
  await client.query("COMMIT");
  // "Methylphenidate (D,L)" → methylphenidate; "Naltrexone/Bupropion" → both; "Sodium oxybate" → oxybate (sodium alone says little).
  const drugNames = new Set(drugs.flatMap(({ head }) => fold(head.replace(/\(.*\)/u, "")).split(/[/ ]+/u))
    .filter((word) => word.length >= 5 && word !== "sodium"));
  const disorders = new Set(index.map(({ head }) => fold(head.split(/\s*[(,]/u)[0] ?? ""))
    .filter((head) => head.length >= 4 && !/^autres?\b/u.test(head) && !EXCLUDED.has(head) && !/^(?:evaluation|whodas)/u.test(head)));
  if (drugNames.size < 100 || disorders.size < 150) throw new Error(`too few topics (${drugNames.size} drugs, ${disorders.size} disorders): wrong database?`);
  const list = (set) => [...set].sort().map((item) => `  ${JSON.stringify(item)},`).join("\n");
  const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "shared", "alexa", "book-topics.generated.ts");
  writeFileSync(out, `/**
 * ⚠️ GENERATED by \`scripts/gen-book-topics.mjs\` from the approved books' headings — do not edit by hand.
 * Folded (no accents, lower case). Drugs: the prescriber's guide monographs. Disorders: head terms of the DSM's own index,
 * minus everyday, record and scaffolding words (see the generator). Used only to send a question to the books.
 */
export const BOOK_DRUG_NAMES: readonly string[] = [
${list(drugNames)}
];

export const BOOK_DISORDER_TERMS: readonly string[] = [
${list(disorders)}
];
`);
  console.log(`book topics written: ${drugNames.size} drugs, ${disorders.size} disorder terms`);
} finally {
  await client.end();
}
