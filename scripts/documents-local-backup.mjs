import {execFileSync} from "node:child_process";
import {randomBytes,scryptSync,createCipheriv,createDecipheriv,createHash} from "node:crypto";
import {mkdirSync,writeFileSync,readFileSync} from "node:fs";
import path from "node:path";
const dir=path.resolve(".superpowers/sdd/2026-10-07-documents-editor");mkdirSync(dir,{recursive:true});
const phrase=randomBytes(32).toString("base64");
const protectedKey=execFileSync("pwsh.exe",["-NoProfile","-Command","$taskKey=[Console]::In.ReadToEnd();ConvertFrom-SecureString (ConvertTo-SecureString $taskKey -AsPlainText -Force)"],{input:phrase,encoding:"utf8"}).trim();
writeFileSync(path.join(dir,"pre-documents-backup-key.dpapi"),protectedKey);
const dump=execFileSync("docker",["exec","mc-p3","pg_dump","-U","postgres","-Fc","mindcare"],{maxBuffer:256*1024*1024});
const salt=randomBytes(16),iv=randomBytes(12),key=scryptSync(phrase,salt,32),cipher=createCipheriv("aes-256-gcm",key,iv);
const encrypted=Buffer.concat([Buffer.from("MCBK1\0\0\0","binary"),salt,iv,cipher.update(dump),cipher.final(),cipher.getAuthTag()]);
const file=path.join(dir,"pre-documents-20261007.dump.enc");writeFileSync(file,encrypted);
const saved=readFileSync(file),decipher=createDecipheriv("aes-256-gcm",key,saved.subarray(24,36));decipher.setAuthTag(saved.subarray(-16));
const recovered=Buffer.concat([decipher.update(saved.subarray(36,-16)),decipher.final()]);
if(!recovered.equals(dump))throw new Error("BackupRoundtripFailed");
const verifyDb="mindcare_documents_backup_verify_20261007";
execFileSync("docker",["exec","mc-p3","createdb","-U","postgres",verifyDb]);
execFileSync("docker",["exec","-i","mc-p3","pg_restore","-U","postgres","--exit-on-error","-d",verifyDb],{input:recovered,maxBuffer:64*1024*1024});
const sql="SELECT count(*)::text||':'||md5(coalesce(string_agg(id::text||coalesce(content_hash,'')||rendered_html,'' ORDER BY id),'')) FROM app.documents";
const fingerprint=db=>execFileSync("docker",["exec","mc-p3","psql","-U","postgres","-d",db,"-tA","-c",sql],{encoding:"utf8"}).trim();
const before=fingerprint("mindcare"),after=fingerprint(verifyDb);if(before!==after)throw new Error("DocumentBackupMismatch");
writeFileSync(path.join(dir,"pre-documents-fingerprint.txt"),before);
console.log("DOCUMENT BACKUP RESTORE PASS",createHash("sha256").update(encrypted).digest("hex"));
